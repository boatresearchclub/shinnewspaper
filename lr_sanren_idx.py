# 選手×会場×コースの期待3連対率を取得
# ============================================================

def _get_expected_3ren(
    name: str,
    venue: str,
    course_str: str,
    venue_course_master: dict,
) -> float:
    """
    venue_course_master から「この会場・このコースでの平均3連対率」を返す。

    優先順位:
        1. 同選手の同会場×同コース実績（最も精度が高い）
        2. 同会場×同コースの全選手平均（マスタから逆算）
        3. 全国コース別デフォルト（フォールバック）

    ※ venue_course_master のキーは (選手名, 会場名, コース文字列)
       値のdictには "3連対率" または "3連対率%" などのキーが存在する想定。
       実際のキー名はマスタの列名に依存するため複数キーを試みる。
    """
    # ── 優先①: 同選手の会場×コース実績 ─────────────────────────────────
    row = None
    if venue_course_master:
        # 完全一致
        row = venue_course_master.get((name, venue, course_str))
        # 4文字前方一致フォールバック（lr_masters の命名規則に準拠）
        if row is None and len(name) >= 5:
            row = venue_course_master.get((name[:4], venue, course_str))

    if row is not None:
        for key in ("3連対率", "3連対率%", "3着以内率", "win3_rate", "rate_3ren"):
            v = safe_float(row.get(key))
            if v is not None:
                # 0〜1 形式を % に統一
                return v * 100.0 if v <= 1.0 else v

    # ── 優先②: 同会場×同コースの全選手平均 ─────────────────────────────
    if venue_course_master:
        rates = []
        for (nm, kj, cs), r in venue_course_master.items():
            if kj != venue or cs != course_str:
                continue
            # エイリアスキー（4文字名）は重複するため元の名前のみカウント
            if len(nm) < len(name) and name.startswith(nm):
                continue
            for key in ("3連対率", "3連対率%", "3着以内率", "win3_rate", "rate_3ren"):
                v = safe_float(r.get(key))
                if v is not None:
                    rates.append(v * 100.0 if v <= 1.0 else v)
                    break
        if rates:
            return round(sum(rates) / len(rates), 2)

    # ── フォールバック③: 全国コース別デフォルト ─────────────────────────
    return _NATIONAL_3REN_BY_COURSE.get(course_str, 50.0)


