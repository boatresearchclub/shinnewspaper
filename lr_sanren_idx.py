def _calc_fly_survival_score(
    results: list[dict],
    main_winner_waku: str | None,
) -> dict[str, float]:
    """
    飛び展開専用の上位残存スコアを6艇分計算して返す。

    【設計思想】
    飛び展開では「1着艇番との物理的コース距離」が
    残り5艇の3着以内残存確率を強く規定する（実測より）。
    _FLY_SURVIVAL_TABLE の実測値をベースに、選手の abs_win3
    （本質的ポテンシャル）でブレンドして最終スコアを出す。

    Parameters
    ----------
    results          : 6艇データリスト（abs_win3, waku を持つ）
    main_winner_waku : 飛び展開での予測1着艇番（rel_win1 最大の非1号艇）
                       None の場合はポテンシャルのみで評価

    Returns
    -------
    {waku: float 0〜100} の辞書
    """
    if not results:
        return {}

    # main_winner_waku が None の場合: rel_win1 最大の非1号艇を推定
    if main_winner_waku is None:
        best_waku, best_rel = None, -1.0
        for r in results:
            waku = str(r.get("waku", "")).strip()
            if waku == "1":
                continue
            rel = float(r.get("rel_win1") or 0.0)
            if rel > best_rel:
                best_rel, best_waku = rel, waku
        main_winner_waku = best_waku or "2"

    survival_table = _FLY_SURVIVAL_TABLE.get(main_winner_waku, {})

    # 各艇の abs_win3 を収集してブレンド比率を決める
    abs_win3_list = [float(r.get("abs_win3") or 0.0) for r in results]
    max_abs = max(abs_win3_list) if abs_win3_list else 1.0

    raw_scores: dict[str, float] = {}
    for r in results:
        waku = str(r.get("waku", "")).strip()
        if waku == main_winner_waku:
            # 1着予測艇は除外対象にならないので最高スコアを付与
            raw_scores[waku] = 1.0
            continue

        # ① コース距離スコア（実測残存率）
        dist_score = survival_table.get(waku, 0.40)  # データなし→中央値

        # ② 選手ポテンシャルスコア（abs_win3 を正規化）
        abs_win3 = float(r.get("abs_win3") or 0.0)
        win3_floor = _NATIONAL_3REN_BY_COURSE.get(
            str(r.get("course", waku)).strip(), 50.0
        ) * _WIN3_FLOOR_RATIO
        abs_win3_floored = max(abs_win3, win3_floor)
        pot_score = min(abs_win3_floored / max(max_abs, 1.0), 1.0)

        # ブレンド: コース距離60% + ポテンシャル40%
        # 根拠: 飛び展開では位置関係が支配的だが実力も無視できない
        blended = dist_score * 0.60 + pot_score * 0.40
        raw_scores[waku] = blended

    # 6艇内 min-max 正規化 → 0〜100
    vals = list(raw_scores.values())
    v_min, v_max = min(vals), max(vals)
    span = v_max - v_min

    normalized: dict[str, float] = {}
    for waku, v in raw_scores.items():
        if span > 1e-6:
            normalized[waku] = round((v - v_min) / span * 100.0, 1)
        else:
            normalized[waku] = 50.0

    return normalized


