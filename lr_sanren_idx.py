# 会場荒れ係数の算出
# ============================================================

def _calc_arare_coeff(venue: str, venue_stats_master: dict) -> float:
    """
    会場の「荒れやすさ」を係数（0.85〜1.15）として返す。

    係数 > 1.0: 荒れやすい会場 → 実力差が出やすい → 高3連対率の選手を際立てる
    係数 < 1.0: 堅い会場（逃げ強） → 1Cの高3連対率は構造的 → 割り引く
    係数 = 1.0: 標準的な会場

    【算出ロジック】
    1コース1着率が高い会場 = 堅い = 係数を下げる（高率は「コースのおかげ」）
    荒れスコアが高い会場  = 荒れ = 係数を上げる（高率は「実力のおかげ」）

    係数範囲を±15%に抑えることで指数の暴れを防ぐ。
    """
    vs = venue_stats_master.get(venue, {}) if venue_stats_master else {}
    if not vs:
        return 1.0

    # 1コース1着率（キー名は lr_masters の正規化ロジックで複数形式が登録済み）
    c1_rate = None
    for key in ("1コース1着率", "1C_1着率", "1コース_1着率"):
        v = safe_float(vs.get(key))
        if v is not None:
            c1_rate = v
            break

    # 荒れスコア（全レース平均、複数Rのスコアを平均して使用）
    arare_scores = []
    for r_no in range(1, 13):
        v = safe_float(vs.get(f"{r_no}R荒れスコア"))
        if v is not None:
            arare_scores.append(v)
    avg_arare = sum(arare_scores) / len(arare_scores) if arare_scores else None

    coeff = 1.0

    # 1C率による補正（全国平均を55%と仮定）
    if c1_rate is not None:
        # 1C率が高いほど係数を下げる（上限/下限を±0.10に制限）
        c1_diff = (c1_rate - 55.0) / 100.0   # 全国平均55%との乖離
        coeff -= c1_diff * 0.5                 # 10%ズレで±0.05の補正
        coeff = max(0.90, min(1.10, coeff))

    # 荒れスコアによる追加補正（荒れスコアの想定範囲: 0〜100）
    if avg_arare is not None:
        # 荒れスコア50を中央として、高いほど係数を上げる
        arare_diff = (avg_arare - 50.0) / 100.0
        coeff += arare_diff * 0.10             # 50点ズレで±0.05の補正
        coeff = max(0.85, min(1.15, coeff))    # 最終範囲を±15%に制限

    return round(coeff, 4)


