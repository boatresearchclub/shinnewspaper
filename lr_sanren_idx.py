# 全国平均1コース1着率（基準）
_NATIONAL_C1_WIN1_RATE: float = 55.0


def _calc_venue_bias_coeffs(
    venue: str,
    venue_stats_master: dict,
) -> dict[str, float]:
    """
    会場のコースバイアス補正係数テーブルを返す。

    【v5優先順位】
    優先①: _VENUE_BIAS_OVERRIDE に会場固有係数が定義されている場合はそれを返す。
            （実データ検証で3C誤除外率50%超など固有バイアスが強い会場向け）
    優先②: venue_stats_master の1コース1着率から動的生成する。
    フォールバック: データなし → 全国平均基準係数 _COURSE_BIAS_BASE をそのまま返す。

    【動的生成ロジック（優先②）】
    - 全国平均1C率(55%)を基準としてスケール係数を計算。
    - 1C率が高い会場（逃げ強）= インコースバイアスが大きい = 補正を強める。
    - 1C率が低い会場（荒れ）  = インコースバイアスが小さい = 補正を弱める。
    - スケール係数は 0.5〜1.5 にクリップ（暴れ防止）。
    - 最終係数クリップ: v4の0.80〜1.20 → v5の0.75〜1.25に拡大
      （基準係数強化後に補正が潰れる問題を解消）
    """
    # ── 優先①: 会場固有オーバーライド ─────────────────────────────────────
    if venue in _VENUE_BIAS_OVERRIDE:
        override = dict(_VENUE_BIAS_OVERRIDE[venue])
        override.setdefault("1", 1.00)  # 1Cは補正なし
        return override

    # ── 優先②: 1C率から動的生成 ─────────────────────────────────────────
    vs = venue_stats_master.get(venue, {}) if venue_stats_master else {}

    c1_rate: float | None = None
    if vs:
        for key in ("1コース1着率", "1C_1着率", "1コース_1着率"):
            v = safe_float(vs.get(key))
            if v is not None:
                c1_rate = v
                break

    if c1_rate is None:
        # データなし → 全国平均基準係数をそのまま返す
        return dict(_COURSE_BIAS_BASE)

    # スケール係数: 全国平均(55%)からの乖離に比例、0.5〜1.5にクリップ
    scale = 1.0 + (c1_rate - _NATIONAL_C1_WIN1_RATE) / _NATIONAL_C1_WIN1_RATE
    scale = max(0.5, min(1.5, scale))

    result: dict[str, float] = {}
    for course_str, base_coeff in _COURSE_BIAS_BASE.items():
        bias_dev       = base_coeff - 1.0
        scaled_dev     = bias_dev * scale
        venue_coeff    = 1.0 + scaled_dev
        # v5: クリップ幅を 0.80〜1.20 → 0.75〜1.25 に拡大
        # （v4では基準係数強化後の補正がクリップで潰れていた）
        result[course_str] = round(max(0.75, min(1.25, venue_coeff)), 4)

    return result

