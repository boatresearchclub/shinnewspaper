def _calc_st_adj(avg_st: float | None, course_str: str) -> float:
    """
    平均STとコースから「推定3着率への加減算値（%ポイント）」を返す。

    avg_st が None の場合は 0.0（補正なし）。

    【設計思想】
    旧係数方式（乗算）は ST・展開・バイアスが複合すると膨張する。
    %ポイント加算に統一することで 0〜100% の範囲内に自然に収まる。

    【補正量の根拠】
    0.01秒の遅れが3着率に与える影響（コース別統計から）:
      1C: ±1.0pt  （逃げ体勢に入れるため実質影響小）
      2C: ±1.5pt
      3C: ±2.0pt
      4C: ±2.5pt
      5C: ±3.0pt  （差し・まくりが決まらず詰まる）
      6C: ±3.5pt
    最大クリップ: ±3〜12pt（コース別）
    """
    if avg_st is None:
        return 0.0

    national_avg = _NATIONAL_AVG_ST_BY_COURSE.get(course_str, 0.20)
    st_diff = avg_st - national_avg  # 正=遅い、負=速い

    # 0.01秒あたりの%ポイント感度
    _ST_PT_SENS: dict[str, float] = {
        "1": 100.0, "2": 150.0, "3": 200.0,
        "4": 250.0, "5": 300.0, "6": 350.0,
    }
    sensitivity = _ST_PT_SENS.get(course_str, 200.0)

    adj = -(st_diff * sensitivity)   # 遅いほどマイナス

    # コース別クリップ
    _ST_CLIP: dict[str, float] = {
        "1": 3.0, "2": 5.0, "3": 7.0, "4": 9.0, "5": 11.0, "6": 12.0,
    }
    clip = _ST_CLIP.get(course_str, 8.0)
    return round(max(-clip, min(clip, adj)), 2)


