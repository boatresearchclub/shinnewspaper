# 展開ペナルティ係数の算出（第4層）
# ============================================================

def _calc_tenkai_adj(
    waku: str,
    cascade_scores: dict[str, dict] | None,
    nige_prob: float,
) -> float:
    """
    展開連鎖後の3着スコアから「推定3着率への加減算値（%ポイント）」を返す。

    cascade_scores なし → 0.0（補正なし）
    1号艇（逃げ確率高い）→ 0.0（展開補正対象外）

    【設計思想】
    旧係数方式（0.60〜1.20倍）を廃止し、展開有利/不利を
    最大±15%ポイントの加減算として表現する。

    6艇内での相対位置（0=最下位〜1=最上位）を
    -15pt〜+15pt にリニアマッピング:
        最上位（展開最有利）: +15pt
        中位（影響なし）    :   0pt
        最下位（展開詰まり）: -15pt

    ±15ptの根拠: 実際の3着率変動の経験的上限が±15%程度。
    """
    if not cascade_scores:
        return 0.0

    fly_prob = 1.0 - nige_prob

    all_scores: dict[str, float] = {}
    for w, sc in cascade_scores.items():
        s_nige = sc.get("逃げ_3着") or sc.get("3着", 0.0)
        s_main = sc.get("主役_3着") or sc.get("3着", 0.0)
        all_scores[w] = s_nige * nige_prob + s_main * fly_prob

    if not all_scores:
        return 0.0

    score = all_scores.get(waku)
    if score is None or (waku == "1" and score <= 0.0):
        return 0.0

    vals  = list(all_scores.values())
    s_min = min(vals)
    s_max = max(vals)
    span  = s_max - s_min

    if span < 1e-6:
        return 0.0

    # 相対位置 0〜1 → -15pt〜+15pt
    rel = (score - s_min) / span
    adj = (rel - 0.5) * 30.0   # 中央=0, 最上位=+15, 最下位=-15
    return round(max(-15.0, min(15.0, adj)), 2)


